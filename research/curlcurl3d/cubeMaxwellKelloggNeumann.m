%% Maxwell interface problem on cube
% Neumann boundary problem using Kellogg potential u = nabla phi
%   Reference: Cai, Zhiqiang, and Shuhao Cao. "A recovery-based a posteriori error estimator for H(curl) interface problems." Computer Methods in Applied Mechanics and Engineering 296 (2015): 169-195.
%
%  Copyright (C) Long Chen. See COPYRIGHT.txt for details.
%% Parameters
clear; close all;
maxNdof = 1e5;
theta = 0.35;
maxIt = 200;
reltol = 6e-2; % for gamma = 0.5, u = \nabala phi \in H^{eps} eps<0.5
% reltol = 0.45; % for gamma = 0.1, u \in H^{eps}, eps<0.1 
estimatefunction = @recoverycurlcurl3;
% estimatefunction = @residualcurlcurl3;

%% mesh generated by delauneayTri
 
[x,y,z] = ndgrid(-1:1:1,-1:1:1,-0.2:0.4:0.2);
node = [x(:),y(:),z(:)];
matlabversion = version;
T = delaunayTriangulation(x(:),y(:),z(:));
elem = T.ConnectivityList;

elem = label3(node,elem);
N0 = size(node,1);
HB(1:N0,1:3) = repmat((1:N0)',1,3); 
HB(1:N0,4) = 0;

%% PDE and boundary conditions
bdFlag = setboundary3(node,elem,'Neumann');
pde = dataMaxwellKellogg(0.5);

%% Error estimation assessment initialization
Ndof = zeros(maxIt,1);
errEnergy = zeros(maxIt,1);
errEnergySigma = zeros(maxIt,1);
errEnergy_compare = zeros(maxIt,1);

etaTotal = zeros(maxIt,1);
etaSolTotal = zeros(maxIt,1);
etaIrrotTotal = zeros(maxIt,1);

tanjumpTotal = zeros(maxIt,1);
norjumpTotal = zeros(maxIt,1);

elemresTotal = zeros(maxIt,1);
edgejumpTotal = zeros(maxIt,1);

%energyNorm uses integration instead the discrete bilinear form
energyNorm = zeros(maxIt,1);
energyNorm_compare = zeros(maxIt,1);

for k=1:maxIt
    fprintf('\nNumber of refinements is %2d. \n',k);
    
    %% Solve
    option.solver = 'direct';
    uh = eddycurrent3(node,elem,bdFlag,pde,option);
    Ndof(k) = size(uh,1);
    
    %% Plot the mesh
    figure(1); 
    set(gcf, 'Position', [200 600 1200 1000])
    subplot(2,2,1)
    hold on;
    showboundary3(node,elem,'(x>=0)','edgecolor','black','facealpha',0.5);
    
    subplot(2,2,2)
    hold on;
    showboundary3(node,elem,'(z<=0)','edgecolor','black','facealpha',0.5);
    
    subplot(2,2,3)
    hold on;
    showboundary3(node,elem,'(y>=0)','edgecolor','black','facealpha',0.5);
    
    %% Error estimation
    [etap, eta0, resK, divJK] = estimatefunction(node,elem,uh,pde);
    eta = sqrt(etap.^2 + eta0.^2 + resK.^2 + divJK.^2);

    edgejump = sqrt(etap.^2 + eta0.^2);
    elemres = sqrt(resK.^2 + divJK.^2);
    etaSol = sqrt(etap.^2 + resK.^2);
    etaIrrot = sqrt(eta0.^2 + divJK.^2);
    
    elemresTotal(k) = norm(elemres);
    edgejumpTotal(k) = norm(edgejump);
    tanjumpTotal(k) = norm(etap);
    norjumpTotal(k) = norm(eta0);
    etaTotal(k) = norm(eta);
    etaSolTotal(k) = norm(etaSol);
    etaIrrotTotal(k) = norm(etaIrrot);
    
    %% True error
    [errEnergy(k), errK] = getEnergyerrorNd0boundary(node,elem,pde,uh);
    [errEnergy_compare(k), errK_compare]= getEnergyerrorNd0(node,elem,pde,uh);
    
    uh_0 = zeros(size(uh,1),1);
    [energyNorm(k), ~] = getEnergyerrorNd0boundary(node,elem,pde,uh_0);
    [energyNorm_compare(k), ~] = getEnergyerrorNd0(node,elem,pde,uh_0);
    
    %% Print the results in this refinement
    fprintf('(Error Estimator)/(Energy Error) is %6g in this refinement. \n', etaTotal(k)/errEnergy(k));
    fprintf('(Solenoidal Eta)/(Energy Error) is %6g in this refinement. \n', etaSolTotal(k)/errEnergy(k));
    fprintf('(Irrotational Eta)/(Energy Error) is %6g in this refinement. \n', etaIrrotTotal(k)/errEnergy(k));
    fprintf('(Normal Jump+Tangential Jump)/(Energy Error) is %6g in this refinement. \n', edgejumpTotal(k)/errEnergy(k));
    fprintf('(Tangential jump)/(Energy Error) is %6g in this refinement. \n', tanjumpTotal(k)/errEnergy(k));
    fprintf('(Normal jump)/(Energy Error) is %6g in this refinement. \n', norjumpTotal(k)/errEnergy(k));
    fprintf('(Equation residual+Divergence Residual)/(Energy Error) is %6g in this refinement. \n', elemresTotal(k)/errEnergy(k));
    fprintf('Relative Error of FEM is %5g before next refinement. \n', errEnergy(k)/energyNorm(k));
    
    %% Stop criterion
    if (errEnergy(k)/energyNorm(k) <= reltol)
        break;
    elseif (Ndof(k)>maxNdof)
        break;
    end
    
    %% Mark and refine
    markedElem = mark(elem,eta,theta);
    
    [node,elem,bdFlag,HB] = bisect3(node,elem,markedElem,bdFlag,HB);
end

%% convergence
Ndof = Ndof(1:k);
energyNorm = energyNorm(1:k);
energyNorm_compare = energyNorm_compare(1:k);
engNorm = energyNorm(k);
engNorm_compare = energyNorm_compare(k);
errEnergy = errEnergy(1:k)/engNorm;
errEnergy_compare = errEnergy_compare(1:k)/engNorm;
errEnergySigma = errEnergySigma(1:k); % Here the sigma's error is not relative
etaTotal = etaTotal(1:k)/engNorm;
elemresTotal = elemresTotal(1:k)/engNorm;
edgejumpTotal = edgejumpTotal(1:k)/engNorm;
tanjumpTotal = tanjumpTotal(1:k)/engNorm;
norjumpTotal = norjumpTotal(1:k)/engNorm;

subplot(2,2,3)
loglog(Ndof,errEnergy,'k-*',...
       Ndof,etaTotal,'b-o',...
       Ndof,4*Ndof.^(-1/3),'r--',...
       'linewidth',2);
title('Error', 'FontSize', 14);
axis 'auto x'
% xlim([0.8*min(N) 1.1*max(N)]);
grid on
% legend(' ||\beta^{1/2} e_h||_{L^2(\Omega)} + ||\mu^{-1/2}\nabla \times e_h||_{L^2(\Omega)}',...
%      '\eta(u_h)','N^{-1/3}','LOCATION','best')

eff_index = etaTotal./errEnergy;
subplot(2,2,4);
semilogx(Ndof,eff_index,'--*b','LineWidth',1,'MarkerSize',6)
axis([100,100000,0,5]);

fullscreen = get(0,'ScreenSize');
set(gcf,'Position',[0 50 fullscreen(3) fullscreen(4)-100])
set(gcf,'color','w')

%% Convergence rate
figure(2);
   
r1 = showrate(Ndof,etaTotal,6,'b-o');
hold on;
r2 = showrate(Ndof,errEnergy,6,'k-+');
legend('Estimator',['cN^{' num2str(r1) '}'], ...
       'Error',['cN^{' num2str(r2) '}'], ...
       'LOCATION','Best');

return;